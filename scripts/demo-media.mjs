// Generates the demo pack's images (RFC-0036 §3): simple gradient PNGs, stored under the
// content key the playground's demo site uses (`media/<site>/<sha256>`), plus their metadata in
// src/playground/demo-media.ts. Run with `node scripts/demo-media.mjs` after changing IMAGES.
import { createHash } from "node:crypto";
import { mkdir, rm, writeFile } from "node:fs/promises";
import { deflateSync } from "node:zlib";

const SITE_ID = "site_playgrounddemo";
const W = 1200;
const H = 630;
const IMAGES = [
  { slug: "harbour-dawn", title: "Harbour at dawn", from: [246, 130, 31], to: [32, 46, 89] },
  {
    slug: "forest-light",
    title: "Light through the forest",
    from: [52, 168, 83],
    to: [12, 42, 34],
  },
  { slug: "city-dusk", title: "City at dusk", from: [124, 58, 237], to: [236, 72, 153] },
];

const CRC = new Uint32Array(256).map((_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const out = Buffer.alloc(12 + data.length);
  out.writeUInt32BE(data.length, 0);
  out.write(type, 4, "ascii");
  data.copy(out, 8);
  out.writeUInt32BE(crc32(out.subarray(4, 8 + data.length)), 8 + data.length);
  return out;
}
function png({ from, to }) {
  const raw = Buffer.alloc((W * 3 + 1) * H);
  for (let y = 0; y < H; y++) {
    raw[y * (W * 3 + 1)] = 0;
    for (let x = 0; x < W; x++) {
      const t = (x / W) * 0.6 + (y / H) * 0.4;
      for (let c = 0; c < 3; c++)
        raw[y * (W * 3 + 1) + 1 + x * 3 + c] = Math.round(from[c] + (to[c] - from[c]) * t);
    }
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(W, 0);
  ihdr.writeUInt32BE(H, 4);
  ihdr.set([8, 2, 0, 0, 0], 8);
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

const dir = new URL(`../public/demo/media/${SITE_ID}/`, import.meta.url);
await rm(dir, { recursive: true, force: true });
await mkdir(dir, { recursive: true });
const meta = [];
for (const image of IMAGES) {
  const bytes = png(image);
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  await writeFile(new URL(sha256, dir), bytes);
  meta.push({
    slug: image.slug,
    title: image.title,
    sha256,
    bytes: bytes.length,
    width: W,
    height: H,
  });
}
await writeFile(
  new URL("../src/playground/demo-media.ts", import.meta.url),
  `// Generated by scripts/demo-media.mjs; do not edit.\nexport const DEMO_SITE_ID = "${SITE_ID}";\n\nexport const DEMO_MEDIA = ${JSON.stringify(meta, null, 2)} as const;\n`,
);
console.log(meta.map((m) => `${m.slug} ${m.bytes} B ${m.sha256.slice(0, 12)}`).join("\n"));
